package com.jain.core.pudgala;

import java.util.List;

/**
 * Hindi: {@code Paramanu} svaroop.
 * English: Qualitative properties of paramanu from canonical definitions as summarized in Kachhara (2016 §3).
 */
public final class ParamanuNature {

    private ParamanuNature() {}

    public static List<String> definingProperties() {
        return List.of(
                "Indivisible, indestructible, impenetrable, incombustible, imperceptible to ordinary senses",
                "Dimensionless: no length, breadth, depth; no half or middle portion",
                "Pure pudgala: intrinsic colour, taste, smell, and two primary touches (hot/cold and smooth/rough)",
                "Intensity varies by sadguna-hani-vridhi; free-state mutation within same quality family",
                "Apratighati: generally not stopped; does not hinder others; rare collision",
                "Dynamic: spin, vibratory, migratory motion; activity in quanta",
                "Bosonic clustering: infinite paramanus may occupy one space-point in Jain view",
                "Direct unit of pudgala; indirect unit for space, time, and attribute magnitude");
    }
}
