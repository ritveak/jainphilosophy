package com.jain.core.lexicon;

/**
 * Hindi: {@code Shabda} — enum naam Roman lipi mein.
 * English: Enum constant names are Hindi (or Sanskrit–Hindi) transliterations; this method returns the English gloss
 * only.
 */
public interface Lexical {

    /** Short English meaning or gloss for the constant. */
    String englishMeaning();
}
